// -----------------------------------------------------------------------------
// NavigationOptions.cs — البيت الواحد **القابل للتغيير** لسلوك التنقل الافتراضي (RULE-N192)
//
// نفس نمط ThemePalette في الألوان: قيمة تُعلَن مرة واحدة، تُغيَّر بتعديل واحد،
// وتستهلكها كل الشاشات بلا أن تعرفها أو تضبطها بنفسها.
//
// قبل هذا الملف كانت قيم سلوك Enter حرفية داخل KeyboardHelper (بحّة الصف 8 بكسل،
// وترتيب العرض، والخروج إلى زر الوضع)، فكان تغيير أي واحدة منها يستلزم تعديل
// منطق التنقل نفسه. الآن:
//
//     NavigationOptions (القيم الافتراضية الحيّة)
//            ↓
//     KeyboardHelper.WireEnterAsTab(scope, primaryButton) — يقرأها عند كل ضغطة
//            ↓
//     الشاشات (بلا تغيير: لا تعرف هذه القيم ولا تضبطها)
//
// قواعد ملزمة:
//   • لا ألوان ولا واجهة ولا آثار جانبية — إعدادات سلوكية فقط.
//   • لا تضبطها أي شاشة: تغييرها يحدث هنا مرة واحدة (أو من شاشة إعدادات مستقبلية).
//   • التغيير يسري فوراً بلا إعادة تشغيل وبلا إعادة فتح الشاشات، لأن مستهلكها
//     يقرأ القيم عند كل ضغطة مفتاح لا مرة واحدة.
// -----------------------------------------------------------------------------

namespace SalesSystem.Desktop.Helpers;

/// <summary>
/// البيت الواحد لقيم التنقل الافتراضية المشتركة (<c>RULE-N192</c>) — يُستهلك حصراً من
/// <see cref="KeyboardHelper.WireEnterAsTab(Control, Func{Button?})"/>.
/// <para>
/// <b>لا تضبط أي شاشة هذه القيم</b>: هي افتراضيات نظامية تُعلَن هنا مرة واحدة، فتغييرها
/// في هذا الملف (أو من شاشة إعدادات مستقبلية) يسري على كل من يستهلكها بلا لمس أي شاشة،
/// وبلا نسخة ثانية من المنطق في أي مكان (<c>RULE-N169</c>…<c>RULE-N172</c>).
/// </para>
/// <para>
/// <b>تُقرأ حيّة عند كل ضغطة مفتاح</b> لا مرة واحدة: تغيير أي قيمة هنا يظهر فوراً في
/// الشاشات المفتوحة بلا إعادة تشغيل التطبيق.
/// </para>
/// </summary>
public static class NavigationOptions
{
    // ═════════════════════════════════════════════════════════════════
    //  الافتراضيات المعلنة مرة واحدة (لا رقم سحري ولا قيمة مكرّرة)
    // ═════════════════════════════════════════════════════════════════

    /// <summary>الافتراضي: Enter يتبع ترتيب العرض (صفوف من الأعلى للأسفل، RTL من اليمين لليسار).</summary>
    private const bool DefaultEnterFollowsDisplayOrder = true;

    /// <summary>الافتراضي: بعد آخر حقل ينتقل التركيز إلى زر الوضع الحالي بدل الدوران لأول حقل.</summary>
    private const bool DefaultEnterExitsToModeButton = true;

    /// <summary>الافتراضي: أقصى فرق رأسي (بكسل) يجعل الحقلين في الصف نفسه.</summary>
    private const int DefaultRowBandTolerancePixels = 8;

    // ═════════════════════════════════════════════════════════════════
    //  القيم الحيّة (تُقرأ عند كل ضغطة — تُغيَّر بتعديل واحد)
    // ═════════════════════════════════════════════════════════════════

    /// <summary>
    /// هل يتبع <c>Enter</c> ترتيب <b>العرض</b> (الافتراضي <c>true</c>)؟
    /// <para>
    /// <c>true</c> = ترتيب العرض: صفاً صفاً من الأعلى إلى الأسفل، وفي كل صف من اليمين إلى اليسار
    /// عند <c>RightToLeft.Yes</c> (ومن اليسار إلى اليمين خلافه) — وهو الافتراضي الذي يراه المستخدم الآن.
    /// </para>
    /// <para>
    /// <c>false</c> = يتبع ترتيب <c>TabIndex</c> المعلن في المصمّم عبر <c>SelectNextControl</c>،
    /// لا ترتيب العرض على الشاشة.
    /// </para>
    /// تُقرأ حيّة عند كل ضغطة.
    /// </summary>
    public static bool EnterFollowsDisplayOrder { get; set; } = DefaultEnterFollowsDisplayOrder;

    /// <summary>
    /// هل ينتقل التركيز بعد آخر حقل إلى <b>زر الوضع الحالي</b> (الافتراضي <c>true</c>)؟
    /// <para>
    /// <c>true</c> = تركيز الزر الأساسي للوضع فقط (بلا <c>PerformClick</c> — لا حفظ بـ<c>Enter</c>)،
    /// وإن لم يكن متاحاً يرجع إلى أول حقل في السلسلة.
    /// </para>
    /// <para>
    /// <c>false</c> = لا خروج إلى الزر: يدور التركيز إلى أول حقل في السلسلة دائماً.
    /// </para>
    /// تُقرأ حيّة عند كل ضغطة.
    /// </summary>
    public static bool EnterExitsToModeButton { get; set; } = DefaultEnterExitsToModeButton;

    /// <summary>
    /// أقصى فرق رأسي بالبكسل (الافتراضي <c>8</c>) بين حقلين ليُعدّا في الصف نفسه عند
    /// ترتيب التنقل بترتيب العرض؛ ويبقى الحد الفعلي هو الأكبر من هذه القيمة ومن نصف ارتفاع
    /// أول حقل في الصف (فالحقول الكبيرة تُقسِّم صفوفها بنفسها).
    /// تُقرأ حيّة عند كل ضغطة. القيمة الأصغر من <c>1</c> تُعامل كأنها الحد الأدنى من ارتفاع الحقل.
    /// </summary>
    public static int RowBandTolerancePixels { get; set; } = DefaultRowBandTolerancePixels;

    /// <summary>
    /// يُعيد القيم الثلاث إلى افتراضياتها المعلنة أعلاه — نقطة استرجاع واحدة
    /// (لم تُستهلك بعد؛ موجودة لشاشة إعدادات مستقبلية بلا منطق مكرّر في أي مكان).
    /// </summary>
    public static void ResetToDefaults()
    {
        EnterFollowsDisplayOrder = DefaultEnterFollowsDisplayOrder;
        EnterExitsToModeButton = DefaultEnterExitsToModeButton;
        RowBandTolerancePixels = DefaultRowBandTolerancePixels;
    }
}
